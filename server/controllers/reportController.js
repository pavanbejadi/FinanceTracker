import PDFDocument from "pdfkit";
import Transaction from "../models/Transaction.js";
import Budget from "../models/Budget.js";
import { summarizeTransactions } from "../services/financeAnalyzer.js";

const formatCurrency = (value) =>
  `INR ${Number(value || 0).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

const formatStatementDate = (value) =>
  new Date(value).toLocaleDateString("en-IN", {
    day: "2-digit",
    month: "short",
    year: "numeric",
  });

const drawStatementHeader = (doc, period, pageWidth) => {
  doc
    .fillColor("#12304a")
    .font("Helvetica-Bold")
    .fontSize(20)
    .text("FINTRACK", 48, 42, { characterSpacing: 1.2 });
  doc
    .fillColor("#536779")
    .font("Helvetica")
    .fontSize(9)
    .text("PERSONAL FINANCE STATEMENT", 48, 68);
  doc
    .fillColor("#172b3a")
    .font("Helvetica-Bold")
    .fontSize(16)
    .text("Monthly Account Statement", 48, 101);
  doc
    .fillColor("#536779")
    .font("Helvetica")
    .fontSize(10)
    .text(`Statement period  ${period}`, 48, 125);
  doc
    .moveTo(48, 147)
    .lineTo(pageWidth - 48, 147)
    .lineWidth(1)
    .strokeColor("#d8e1e8")
    .stroke();
};

const drawTableHeader = (doc, y, columns) => {
  doc.rect(48, y, 516, 25).fill("#edf3f7");
  doc.fillColor("#344b5e").font("Helvetica-Bold").fontSize(8);
  columns.forEach((column) => {
    doc.text(column.label, column.x, y + 8, {
      width: column.width,
      align: column.align || "left",
    });
  });
  return y + 25;
};

const drawPageFooter = (doc, pageWidth, pageHeight, pageNumber) => {
  doc
    .moveTo(48, pageHeight - 42)
    .lineTo(pageWidth - 48, pageHeight - 42)
    .lineWidth(0.7)
    .strokeColor("#d8e1e8")
    .stroke();
  doc
    .fillColor("#718292")
    .font("Helvetica")
    .fontSize(8)
    .text("Generated by FinTrack", 48, pageHeight - 31, { lineBreak: false });
  doc.text(`Page ${pageNumber}`, pageWidth - 100, pageHeight - 31, {
    width: 52,
    align: "right",
    lineBreak: false,
  });
};

const drawSummary = (doc, report, y) => {
  const cards = [
    { label: "TOTAL CREDITS", value: formatCurrency(report.totalIncome), color: "#147a55" },
    { label: "TOTAL DEBITS", value: formatCurrency(report.totalExpense), color: "#b44747" },
    { label: "NET MOVEMENT", value: formatCurrency(report.savings), color: "#12304a" },
  ];
  const cardWidth = 164;
  cards.forEach((card, index) => {
    const x = 48 + index * 176;
    doc.roundedRect(x, y, cardWidth, 55, 5).fill("#f5f8fa");
    doc.fillColor("#647789").font("Helvetica-Bold").fontSize(7).text(card.label, x + 10, y + 10);
    doc.fillColor(card.color).font("Helvetica-Bold").fontSize(11).text(card.value, x + 10, y + 27, {
      width: cardWidth - 20,
      lineBreak: false,
    });
  });
};

const writeStatementPdf = (res, report) => {
  const doc = new PDFDocument({ size: "A4", margins: { top: 48, bottom: 54, left: 48, right: 48 }, bufferPages: true });
  const pageWidth = doc.page.width;
  const pageHeight = doc.page.height;
  const columns = [
    { label: "DATE", x: 56, width: 58 },
    { label: "DESCRIPTION", x: 119, width: 151 },
    { label: "CATEGORY", x: 275, width: 62 },
    { label: "DEBIT", x: 341, width: 64, align: "right" },
    { label: "CREDIT", x: 411, width: 64, align: "right" },
    { label: "RUNNING NET", x: 481, width: 74, align: "right" },
  ];

  doc.pipe(res);
  drawStatementHeader(doc, report.period, pageWidth);
  drawSummary(doc, report, 163);
  doc.fillColor("#172b3a").font("Helvetica-Bold").fontSize(11).text("Transaction activity", 48, 238);
  doc.fillColor("#718292").font("Helvetica").fontSize(8).text("Running net starts at zero for this period; no opening account balance is included.", 48, 252);
  let y = drawTableHeader(doc, 270, columns);
  let runningNet = 0;
  const sortedTransactions = [...report.transactions].sort(
    (a, b) => new Date(a.transactionDate) - new Date(b.transactionDate),
  );

  if (!sortedTransactions.length) {
    doc.fillColor("#718292").font("Helvetica").fontSize(10).text("No transactions were recorded during this statement period.", 56, y + 14);
    y += 42;
  }

  sortedTransactions.forEach((item, index) => {
    const isIncome = item.type === "income";
    runningNet += isIncome ? item.amount : -item.amount;
    const description = `${item.title || "Transaction"}${item.description ? ` - ${item.description}` : ""}`;
    const date = formatStatementDate(item.transactionDate);
    const category = item.category || "Other";
    const descriptionHeight = doc.font("Helvetica").fontSize(8.5).heightOfString(description, { width: 147 });
    const categoryHeight = doc.font("Helvetica").fontSize(8.5).heightOfString(category, { width: 58 });
    const rowHeight = Math.max(30, Math.max(descriptionHeight, categoryHeight) + 14);
    if (y + rowHeight > pageHeight - 60) {
      doc.addPage();
      drawStatementHeader(doc, report.period, pageWidth);
      y = drawTableHeader(doc, 163, columns);
    }

    if (index % 2 === 1) doc.rect(48, y, 516, rowHeight).fill("#f8fafb");
    doc.fillColor("#263b4b").font("Helvetica").fontSize(8.5);
    doc.text(date, columns[0].x, y + 9, { width: columns[0].width });
    doc.text(description, columns[1].x, y + 8, { width: columns[1].width, height: rowHeight - 10 });
    doc.text(category, columns[2].x, y + 8, { width: columns[2].width, height: rowHeight - 10 });
    doc.text(isIncome ? "-" : formatCurrency(item.amount), columns[3].x, y + 9, {
      width: columns[3].width,
      align: "right",
      lineBreak: false,
    });
    doc.text(isIncome ? formatCurrency(item.amount) : "-", columns[4].x, y + 9, {
      width: columns[4].width,
      align: "right",
      lineBreak: false,
    });
    doc.fillColor(runningNet < 0 ? "#b44747" : "#263b4b").font("Helvetica-Bold");
    doc.text(formatCurrency(runningNet), columns[5].x, y + 9, {
      width: columns[5].width,
      align: "right",
      lineBreak: false,
    });
    y += rowHeight;
    doc.moveTo(48, y).lineTo(564, y).lineWidth(0.4).strokeColor("#e2e8ed").stroke();
  });

  if (y + 58 > pageHeight - 60) {
    doc.addPage();
    drawStatementHeader(doc, report.period, pageWidth);
    y = 163;
  }
  doc.fillColor("#172b3a").font("Helvetica-Bold").fontSize(9)
    .text("Net movement for period", 300, y + 13, { width: 150, align: "right" });
  doc.fillColor(runningNet < 0 ? "#b44747" : "#147a55").font("Helvetica-Bold").fontSize(10)
    .text(formatCurrency(runningNet), 458, y + 12, { width: 78, align: "right", lineBreak: false });

  const range = doc.bufferedPageRange();
  for (let index = range.start; index < range.start + range.count; index += 1) {
    doc.switchToPage(index);
    drawPageFooter(doc, pageWidth, pageHeight, index + 1);
  }
  doc.end();
};

export const getMonthlyReport = async (req, res) => {
  try {
    const now = new Date();
    const year = Number(req.query.year) || now.getFullYear();
    const month = Number(req.query.month) || now.getMonth() + 1;
    const start = new Date(year, month - 1, 1);
    const end = new Date(year, month, 1);

    const transactions = await Transaction.find({
      userId: req.userId,
      transactionDate: { $gte: start, $lt: end },
    }).sort({ transactionDate: -1 });
    const budget = await Budget.findOne({ userId: req.userId });
    const summary = summarizeTransactions(transactions, budget);

    const report = {
      period: `${year}-${String(month).padStart(2, "0")}`,
      totalIncome: summary.totalIncome,
      totalExpense: summary.totalExpense,
      savings: summary.savings,
      budgetRemaining: summary.budgetRemaining,
      categoryBreakdown: summary.categoryBreakdown,
      monthlyTrend: summary.monthlyTrend,
      transactions,
    };

    if (req.query.format === "pdf") {
      res.setHeader("Content-Type", "application/pdf");
      res.setHeader(
        "Content-Disposition",
        `attachment; filename=finance-report-${report.period}.pdf`,
      );

      writeStatementPdf(res, report);
      return;
    }

    res.status(200).json({
      success: true,
      data: report,
    });
  } catch (error) {
    res.status(500).json({
      success: false,
      message: error.message,
    });
  }
};
